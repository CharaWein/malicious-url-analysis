"""Step 2 — data quality checks. Writes reports/data_quality.md."""
import pandas as pd

from .config import CLASS_ORDER, RANDOM_STATE, REPORTS_DIR


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def check(raw: pd.DataFrame) -> dict:
    url = raw["url"].fillna("")
    lower = url.str.lower()
    stripped = lower.str.replace(r"^https?://", "", regex=True)

    flags = pd.DataFrame({
        "label": raw["label"],
        "starts_http": lower.str.match(r"^https?://"),
        "starts_https": lower.str.startswith("https://"),
        "starts_www": stripped.str.startswith("www."),
    })
    prefix = flags.groupby("label")[["starts_http", "starts_https", "starts_www"]].mean().reindex(CLASS_ORDER)

    dup_urls = raw[raw.duplicated("url", keep=False)]
    conflicting = dup_urls.groupby("url")["label"].nunique()

    stats = {
        "rows": len(raw),
        "null_urls": int(raw["url"].isna().sum()),
        "empty_urls": int((url.str.strip() == "").sum()),
        "whitespace_urls": int((url != url.str.strip()).sum()),
        "duplicate_rows": int(raw.duplicated("url").sum()),
        "conflicting_labels": int((conflicting > 1).sum()),
        "class_counts": raw["label"].value_counts().reindex(CLASS_ORDER),
        "prefix": prefix,
    }

    lines = ["# Data quality report", "", "Generated by `pipeline/quality.py`.", ""]
    lines += ["## Basic checks", "", "| check | value |", "|---|---|"]
    for key in ["rows", "null_urls", "empty_urls", "whitespace_urls", "duplicate_rows", "conflicting_labels"]:
        lines.append(f"| {key} | {stats[key]:,} |")

    lines += ["", "## Class balance", "", "| class | rows | share |", "|---|---|---|"]
    for cls, n in stats["class_counts"].items():
        lines.append(f"| {cls} | {n:,} | {_pct(n / len(raw))} |")

    lines += ["", "## Scheme prefix by class (collection artefact check)", "",
              "| class | starts with http(s):// | starts with https:// | host starts with www. |",
              "|---|---|---|---|"]
    for cls, row in prefix.iterrows():
        lines.append(f"| {cls} | {_pct(row.starts_http)} | {_pct(row.starts_https)} | {_pct(row.starts_www)} |")

    lines += ["", "## 10 random URLs per class", ""]
    for cls in CLASS_ORDER:
        sample = raw.loc[raw["label"] == cls, "url"].sample(10, random_state=RANDOM_STATE)
        lines += [f"### {cls}", "", "```"] + [u[:140] for u in sample] + ["```", ""]

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "data_quality.md").write_text("\n".join(lines), encoding="utf-8")

    print("  scheme prefix share by class:")
    print(prefix.map(_pct).to_string().replace("\n", "\n    "))
    return stats
