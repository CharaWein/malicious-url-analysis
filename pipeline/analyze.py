"""Step 6 — run the hypothesis queries against SQLite, save tables and a figure."""
import re
import sqlite3

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from .config import CLASS_ORDER, DB_PATH, REPORTS_DIR, SQL_DIR

# First four slots of the reference categorical palette, in fixed order.
CLASS_COLORS = dict(zip(CLASS_ORDER, ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]))
INK, MUTED, GRID = "#0b0b0b", "#898781", "#e1e0d9"


def read_queries() -> dict[str, str]:
    text = (SQL_DIR / "hypotheses.sql").read_text(encoding="utf-8")
    parts = re.split(r"^-- name: (\w+)\s*$", text, flags=re.M)
    return {name: sql.strip() for name, sql in zip(parts[1::2], parts[2::2])}


def run() -> dict[str, pd.DataFrame]:
    results = {}
    with sqlite3.connect(DB_PATH) as con:
        for name, sql in read_queries().items():
            results[name] = pd.read_sql_query(sql, con)

    lines = ["# Query results", "", "Generated by `pipeline/analyze.py` from `sql/hypotheses.sql`.", ""]
    for name, df in results.items():
        lines += [f"## {name}", "", df.to_markdown(index=False), ""]
    (REPORTS_DIR / "results.md").write_text("\n".join(lines), encoding="utf-8")

    for name, df in results.items():
        print(f"\n  -- {name}\n    " + df.to_string(index=False).replace("\n", "\n    "))

    plot(results)
    return results


def _bars(ax, df: pd.DataFrame, col: str, title: str, fmt: str) -> None:
    df = df.set_index("label").reindex(CLASS_ORDER)
    values = df[col].astype(float)
    bars = ax.bar(CLASS_ORDER, values, color=[CLASS_COLORS[c] for c in CLASS_ORDER], width=0.62)
    for bar, v in zip(bars, values):
        ax.annotate(fmt.format(v), (bar.get_x() + bar.get_width() / 2, v), xytext=(0, 3),
                    textcoords="offset points", ha="center", va="bottom", fontsize=9, color=INK)
    ax.set_title(title, fontsize=10.5, color=INK, loc="left")
    ax.set_ylim(0, values.max() * 1.18)
    ax.tick_params(colors=MUTED, labelsize=9, length=0)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ["top", "right", "left"]:
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color("#c3c2b7")


def plot(results: dict[str, pd.DataFrame]) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(13, 7.2), facecolor="#fcfcfb")
    panels = [
        (results["h0_artifact"], "pct_with_scheme", "Data quality: % URLs with http(s)://", "{:.1f}%"),
        (results["h1_length"], "median_length", "H1: median URL length (no scheme)", "{:.0f}"),
        (results["h2_ip"], "pct_ip", "H2: % URLs with IP instead of domain", "{:.2f}%"),
        (results["h3_suspicious"], "avg_subdomains", "H3: avg subdomains per host", "{:.2f}"),
        (results["h3_suspicious"], "avg_host_hyphens", "H3: avg hyphens in host", "{:.2f}"),
        (results["h4_https"], "pct_https_among_scheme", "H4: % https among URLs with a scheme", "{:.1f}%"),
    ]
    for ax, (df, col, title, fmt) in zip(axes.flat, panels):
        ax.set_facecolor("#fcfcfb")
        _bars(ax, df, col, title, fmt)
    fig.suptitle("Malicious vs benign URLs: lexical features by class", fontsize=13, color=INK,
                 x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    out = REPORTS_DIR / "figures"
    out.mkdir(parents=True, exist_ok=True)
    fig.savefig(out / "hypotheses.png", dpi=130)
    plt.close(fig)
